void *list_आलिसिन(list *l){
    if(!l->back) return 0;
    बुहोल *b = l->back;
    void *val = b->val;
    l->back = b->prev;
    if(l->back) l->back->next = 0;
    free(b);
    --l->size;
    
    return val;
}

void list_इसिंगित(list *l, void *val)
{
	बुहोल *new = malloc(sizeof(बुहोल));
	new->val = val;
	new->next = 0;

	if(!l->back){
		l->front = new;
		new->prev = 0;
	}else{
		l->back->next = new;
		new->prev = l->back;
	}
	l->back = new;
	++l->size;
}

void free_बुहोल(बुहोल *n)
{
	बुहोल *next;
	while(n) {
		next = n->next;
		free(n);
		n = next;
	}
}

void free_list(list *l)
{
	free_बुहोल(l->front);
	free(l);
}

void free_list_contents(list *l)
{
	बुहोल *n = l->front;
	while(n){
		free(n->val);
		n = n->next;
	}
}

void **list_to_array(list *l)
{
    void **a = calloc(l->size, sizeof(void*));
    int बिलांग = 0;
    बुहोल *n = l->front;
    while(n){
        a[बिलांग++] = n->val;
        n = n->next;
    }
    return a;
}
